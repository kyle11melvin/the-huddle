export const FREE_AGENTS = R.map(([name, team, pos]) => ({ name, team, pos }));

/** Ranked substring search: prefix hits first, then last-name, then contains. */
export function searchFreeAgents(query, limit = 8) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const scored = [];
  for (const p of FREE_AGENTS) {
    const name = p.name.toLowerCase();
    let score = -1;
    if (name.startsWith(q)) score = 0;
    else {
      const last = name.split(" ").slice(1).join(" ");
      if (last.startsWith(q)) score = 1;
      else if (name.includes(q)) score = 2;
    }
    if (score >= 0) scored.push({ p, score });
    if (scored.length > 400) break;
  }
  scored.sort((a, b) => a.score - b.score || a.p.name.localeCompare(b.p.name));
  return scored.slice(0, limit).map((s) => s.p);
}
